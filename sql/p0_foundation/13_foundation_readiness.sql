-- G04: Operational primary-key uniqueness
WITH CHECKS AS (
    SELECT 'CUSTOMERS' AS TABLE_NAME,
           COUNT(*) AS ROW_COUNT,
           COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_KEYS
    FROM RAW.CUSTOMERS
    UNION ALL
    SELECT 'ORDERS',COUNT(*),COUNT(DISTINCT ORDER_ID)
    FROM RAW.ORDERS
    UNION ALL
    SELECT 'SHIPMENTS',COUNT(*),COUNT(DISTINCT SHIPMENT_ID)
    FROM RAW.SHIPMENTS
    UNION ALL
    SELECT 'SHIPMENT_EVENTS',COUNT(*),COUNT(DISTINCT EVENT_ID)
    FROM RAW.SHIPMENT_EVENTS
)
SELECT
    'G04' AS TEST_ID,
    TABLE_NAME,
    ROW_COUNT,
    UNIQUE_KEYS,
    IFF(ROW_COUNT = UNIQUE_KEYS,'PASS','FAIL')
        AS TEST_STATUS
FROM CHECKS
ORDER BY TABLE_NAME;

-- G05: Cross-table referential integrity
WITH CHECKS AS (
    SELECT 'ORDERS_TO_CUSTOMERS' AS RELATIONSHIP,
           COUNT(*) AS ORPHANS
    FROM RAW.ORDERS O
    LEFT JOIN RAW.CUSTOMERS C
      ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.CUSTOMER_ID IS NULL

    UNION ALL

    SELECT 'SHIPMENTS_TO_ORDERS',COUNT(*)
    FROM RAW.SHIPMENTS S
    LEFT JOIN RAW.ORDERS O
      ON S.ORDER_ID = O.ORDER_ID
    WHERE O.ORDER_ID IS NULL

    UNION ALL

    SELECT 'EVENTS_TO_SHIPMENTS',COUNT(*)
    FROM RAW.SHIPMENT_EVENTS E
    LEFT JOIN RAW.SHIPMENTS S
      ON E.SHIPMENT_ID = S.SHIPMENT_ID
    WHERE S.SHIPMENT_ID IS NULL
)
SELECT
    'G05' AS TEST_ID,
    RELATIONSHIP,
    ORPHANS,
    IFF(ORPHANS = 0,'PASS','FAIL') AS TEST_STATUS
FROM CHECKS
ORDER BY RELATIONSHIP;