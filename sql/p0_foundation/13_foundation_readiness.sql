-- G01: Required table inventory
WITH EXPECTED AS (
    SELECT COLUMN1 AS TABLE_SCHEMA, COLUMN2 AS TABLE_NAME
    FROM VALUES
        ('RAW','CUSTOMERS'),
        ('RAW','ORDERS'),
        ('RAW','SHIPMENTS'),
        ('RAW','SHIPMENT_EVENTS'),
        ('MEMORY','CONVERSATION_METADATA'),
        ('MEMORY','SESSION_STATE'),
        ('MEMORY','EPISODIC_MEMORY'),
        ('MEMORY','SEMANTIC_MEMORY'),
        ('MEMORY','MEMORY_AUDIT'),
        ('PROCEDURES','PROCEDURE_CATALOG'),
        ('PROCEDURES','PROCEDURE_VERSIONS'),
        ('EVALUATION','TEST_CASES'),
        ('EVALUATION','TEST_RESULTS')
),
ACTUAL AS (
    SELECT TABLE_SCHEMA, TABLE_NAME
    FROM ECOM_AGENT_MEMORY_DB.INFORMATION_SCHEMA.TABLES
    WHERE TABLE_TYPE = 'BASE TABLE'
      AND TABLE_SCHEMA IN (
          'RAW','MEMORY','PROCEDURES','EVALUATION'
      )
)
SELECT
    'G01' AS TEST_ID,
    (SELECT COUNT(*) FROM EXPECTED) AS EXPECTED_TABLES,
    (SELECT COUNT(*) FROM ACTUAL) AS ACTUAL_TABLES,
    (SELECT COUNT(*) FROM EXPECTED E
       LEFT JOIN ACTUAL A
         ON E.TABLE_SCHEMA = A.TABLE_SCHEMA
        AND E.TABLE_NAME = A.TABLE_NAME
       WHERE A.TABLE_NAME IS NULL) AS MISSING_TABLES,
    (SELECT COUNT(*) FROM ACTUAL A
       LEFT JOIN EXPECTED E
         ON E.TABLE_SCHEMA = A.TABLE_SCHEMA
        AND E.TABLE_NAME = A.TABLE_NAME
       WHERE E.TABLE_NAME IS NULL) AS EXTRA_TABLES,
    IFF(
        EXPECTED_TABLES = 13
        AND ACTUAL_TABLES = 13
        AND MISSING_TABLES = 0
        AND EXTRA_TABLES = 0,
        'PASS','FAIL'
    ) AS TEST_STATUS;

-- G02: Operational row counts
WITH COUNTS AS (
    SELECT 'CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ACTUAL_COUNT,
           100 AS EXPECTED_COUNT FROM RAW.CUSTOMERS
    UNION ALL
    SELECT 'ORDERS', COUNT(*), 500 FROM RAW.ORDERS
    UNION ALL
    SELECT 'SHIPMENTS', COUNT(*), 500 FROM RAW.SHIPMENTS
    UNION ALL
    SELECT 'SHIPMENT_EVENTS', COUNT(*), 2000
    FROM RAW.SHIPMENT_EVENTS
)
SELECT
    'G02' AS TEST_ID,
    TABLE_NAME,
    EXPECTED_COUNT,
    ACTUAL_COUNT,
    IFF(ACTUAL_COUNT = EXPECTED_COUNT,'PASS','FAIL')
        AS TEST_STATUS
FROM COUNTS
ORDER BY TABLE_NAME;

