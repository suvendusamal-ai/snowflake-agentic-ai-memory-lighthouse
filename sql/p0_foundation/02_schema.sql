USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE ECOM_AGENT_MEMORY_WH;
USE DATABASE ECOM_AGENT_MEMORY_DB;
USE SCHEMA RAW;

-- 1. Customers
CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID        VARCHAR(30) NOT NULL,
    CUSTOMER_NAME      VARCHAR(200) NOT NULL,
    EMAIL              VARCHAR(255),
    PHONE              VARCHAR(30),
    CITY               VARCHAR(100),
    STATE              VARCHAR(100),
    COUNTRY            VARCHAR(100) DEFAULT 'INDIA',
    CUSTOMER_STATUS    VARCHAR(30) DEFAULT 'ACTIVE',
    CREATED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_CUSTOMERS PRIMARY KEY (CUSTOMER_ID)
)
COMMENT = 'Synthetic e-commerce customers';

-- 2. Orders
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID                NUMBER(18,0) NOT NULL,
    CUSTOMER_ID             VARCHAR(30) NOT NULL,
    ORDER_DATE              TIMESTAMP_NTZ NOT NULL,
    ORDER_AMOUNT            NUMBER(12,2) NOT NULL,
    CURRENCY                VARCHAR(3) DEFAULT 'INR',
    ORDER_STATUS            VARCHAR(30) NOT NULL,
    PROMISED_DELIVERY_DATE  DATE,
    ACTUAL_DELIVERY_DATE    DATE,
    CREATED_AT              TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT              TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_ORDERS PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_ORDERS_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID)
)
COMMENT = 'Customer order facts and delivery commitments';

-- 3. Shipments
CREATE TABLE IF NOT EXISTS SHIPMENTS (
    SHIPMENT_ID            VARCHAR(40) NOT NULL,
    ORDER_ID               NUMBER(18,0) NOT NULL,
    CARRIER_NAME           VARCHAR(100),
    TRACKING_NUMBER        VARCHAR(100),
    SHIPMENT_STATUS        VARCHAR(40) NOT NULL,
    DISPATCH_DATE          TIMESTAMP_NTZ,
    EXPECTED_DELIVERY_DATE DATE,
    REVISED_DELIVERY_DATE  DATE,
    DELAY_REASON           VARCHAR(100),
    LAST_UPDATED_AT        TIMESTAMP_NTZ,
    CREATED_AT             TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_SHIPMENTS PRIMARY KEY (SHIPMENT_ID),
    CONSTRAINT FK_SHIPMENTS_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID)
)
COMMENT = 'Shipment lifecycle and delay information';

-- 4. Shipment Events
CREATE TABLE IF NOT EXISTS SHIPMENT_EVENTS (
    EVENT_ID          VARCHAR(50) NOT NULL,
    SHIPMENT_ID       VARCHAR(40) NOT NULL,
    EVENT_TIMESTAMP   TIMESTAMP_NTZ NOT NULL,
    EVENT_TYPE        VARCHAR(50) NOT NULL,
    EVENT_LOCATION    VARCHAR(200),
    EVENT_DESCRIPTION VARCHAR(1000),
    EVENT_METADATA    VARIANT,
    CREATED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_SHIPMENT_EVENTS PRIMARY KEY (EVENT_ID),
    CONSTRAINT FK_EVENTS_SHIPMENT
        FOREIGN KEY (SHIPMENT_ID)
        REFERENCES SHIPMENTS(SHIPMENT_ID)
)
COMMENT = 'Chronological shipment tracking events';

-- Standard Snowflake table PK/FK constraints are informational.
