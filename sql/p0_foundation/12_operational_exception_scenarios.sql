USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE ECOM_AGENT_MEMORY_WH;
USE DATABASE ECOM_AGENT_MEMORY_DB;

-- EXC-01: Delayed shipments have revised ETAs and reasons.
SELECT
    'EXC-01' AS TEST_ID,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(
        DELAY_REASON IS NULL
        OR REVISED_DELIVERY_DATE IS NULL
        OR REVISED_DELIVERY_DATE <= EXPECTED_DELIVERY_DATE
    ) AS INVALID_RECORDS,
    IFF(INVALID_RECORDS = 0 AND TOTAL_RECORDS > 0,
        'PASS', 'FAIL') AS TEST_STATUS
FROM RAW.SHIPMENTS
WHERE SHIPMENT_STATUS = 'DELAYED';

-- EXC-02: Lost shipments have corresponding loss events.
SELECT
    'EXC-02' AS TEST_ID,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(E.EVENT_ID IS NULL) AS INVALID_RECORDS,
    IFF(INVALID_RECORDS = 0 AND TOTAL_RECORDS > 0,
        'PASS', 'FAIL') AS TEST_STATUS
FROM RAW.SHIPMENTS S
LEFT JOIN RAW.SHIPMENT_EVENTS E
    ON S.SHIPMENT_ID = E.SHIPMENT_ID
   AND E.EVENT_TYPE = 'PACKAGE_LOST'
WHERE S.SHIPMENT_STATUS = 'LOST';

-- EXC-03: Cancelled orders were never dispatched.
SELECT
    'EXC-03' AS TEST_ID,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(
        S.DISPATCH_DATE IS NOT NULL
        OR S.SHIPMENT_STATUS <> 'NOT_DISPATCHED'
    ) AS INVALID_RECORDS,
    IFF(INVALID_RECORDS = 0 AND TOTAL_RECORDS > 0,
        'PASS', 'FAIL') AS TEST_STATUS
FROM RAW.ORDERS O
JOIN RAW.SHIPMENTS S
    ON O.ORDER_ID = S.ORDER_ID
WHERE O.ORDER_STATUS = 'CANCELLED';

-- EXC-04: Delivered orders have delivery events.
SELECT
    'EXC-04' AS TEST_ID,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(E.EVENT_ID IS NULL) AS INVALID_RECORDS,
    IFF(INVALID_RECORDS = 0 AND TOTAL_RECORDS > 0,
        'PASS', 'FAIL') AS TEST_STATUS
FROM RAW.SHIPMENTS S
LEFT JOIN RAW.SHIPMENT_EVENTS E
    ON S.SHIPMENT_ID = E.SHIPMENT_ID
   AND E.EVENT_TYPE = 'DELIVERED'
WHERE S.SHIPMENT_STATUS = 'DELIVERED';

-- EXC-05: In-transit shipments have no actual delivery.
SELECT
    'EXC-05' AS TEST_ID,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(O.ACTUAL_DELIVERY_DATE IS NOT NULL)
        AS INVALID_RECORDS,
    IFF(INVALID_RECORDS = 0 AND TOTAL_RECORDS > 0,
        'PASS', 'FAIL') AS TEST_STATUS
FROM RAW.SHIPMENTS S
JOIN RAW.ORDERS O
    ON S.ORDER_ID = O.ORDER_ID
WHERE S.SHIPMENT_STATUS = 'IN_TRANSIT';

-- EXC-06: James's order supports a deterministic
-- 48-hour escalation scenario as of 2026-10-11 12:00.
-- The clock is fixed so reruns produce the same result.
SELECT
    'EXC-06' AS TEST_ID,
    S.ORDER_ID,
    MAX(
        IFF(E.EVENT_TYPE = 'WEATHER_DELAY',
            E.EVENT_TIMESTAMP, NULL)
    ) AS EXCEPTION_AT,
    '2026-10-11 12:00:00'::TIMESTAMP_NTZ AS AS_OF_TIME,
    DATEDIFF(
        'hour',
        EXCEPTION_AT,
        AS_OF_TIME
    ) AS HOURS_SINCE_EXCEPTION,
    IFF(
        HOURS_SINCE_EXCEPTION >= 48,
        'ESCALATION_ELIGIBLE',
        'NOT_YET_ELIGIBLE'
    ) AS ESCALATION_STATUS
FROM RAW.SHIPMENTS S
JOIN RAW.SHIPMENT_EVENTS E
    ON S.SHIPMENT_ID = E.SHIPMENT_ID
WHERE S.ORDER_ID = 7821
GROUP BY S.ORDER_ID;