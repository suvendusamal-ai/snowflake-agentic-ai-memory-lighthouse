-- SCENARIO S01:
-- Why is James's order 7821 delayed?

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.ORDER_AMOUNT,
    O.CURRENCY,
    O.ORDER_STATUS,
    S.SHIPMENT_ID,
    S.CARRIER_NAME,
    S.SHIPMENT_STATUS,
    S.EXPECTED_DELIVERY_DATE,
    S.REVISED_DELIVERY_DATE,
    S.DELAY_REASON,
    DATEDIFF(
        'day',
        S.EXPECTED_DELIVERY_DATE,
        S.REVISED_DELIVERY_DATE
    ) AS ETA_DELAY_DAYS
FROM RAW.CUSTOMERS C
JOIN RAW.ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN RAW.SHIPMENTS S
    ON O.ORDER_ID = S.ORDER_ID
WHERE C.CUSTOMER_ID = 'CUST_001'
  AND O.ORDER_ID = 7821;

-- Evidence-backed event timeline
SELECT
    E.EVENT_ID,
    E.EVENT_TIMESTAMP,
    E.EVENT_TYPE,
    E.EVENT_DESCRIPTION,
    E.EVENT_METADATA:source_system::VARCHAR
        AS SOURCE_SYSTEM
FROM RAW.SHIPMENT_EVENTS E
JOIN RAW.SHIPMENTS S
    ON E.SHIPMENT_ID = S.SHIPMENT_ID
JOIN RAW.ORDERS O
    ON S.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_ID = 7821
  AND O.CUSTOMER_ID = 'CUST_001'
ORDER BY E.EVENT_TIMESTAMP, E.EVENT_ID;

-- Ground-truth assertions
WITH SCENARIO AS (
    SELECT
        O.ORDER_ID,
        O.CUSTOMER_ID,
        O.ORDER_AMOUNT,
        S.SHIPMENT_STATUS,
        S.DELAY_REASON,
        S.EXPECTED_DELIVERY_DATE,
        S.REVISED_DELIVERY_DATE
    FROM RAW.ORDERS O
    JOIN RAW.SHIPMENTS S
        ON O.ORDER_ID = S.ORDER_ID
    WHERE O.ORDER_ID = 7821
)
SELECT
    COUNT(*) AS MATCHING_RECORDS,
    COUNT_IF(
        CUSTOMER_ID = 'CUST_001'
        AND ORDER_AMOUNT = 2500
        AND SHIPMENT_STATUS = 'IN_TRANSIT'
        AND DELAY_REASON = 'WEATHER_DELAY'
        AND EXPECTED_DELIVERY_DATE = '2026-10-08'::DATE
        AND REVISED_DELIVERY_DATE = '2026-10-12'::DATE
    ) AS CORRECT_SCENARIO_RECORDS
FROM SCENARIO;