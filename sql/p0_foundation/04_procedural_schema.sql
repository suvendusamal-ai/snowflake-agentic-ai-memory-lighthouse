USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE ECOM_AGENT_MEMORY_WH;
USE DATABASE ECOM_AGENT_MEMORY_DB;
USE SCHEMA PROCEDURES;

CREATE TABLE IF NOT EXISTS PROCEDURE_CATALOG (
    PROCEDURE_ID         VARCHAR(64) NOT NULL,
    PROCEDURE_NAME       VARCHAR(200) NOT NULL,
    BUSINESS_DOMAIN      VARCHAR(100) NOT NULL,
    PROCEDURE_PURPOSE    VARCHAR(2000),
    PROCEDURE_OWNER      VARCHAR(100),
    PROCEDURE_STATUS     VARCHAR(30) DEFAULT 'DRAFT',
    CREATED_AT           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_PROCEDURE_CATALOG
        PRIMARY KEY (PROCEDURE_ID)
)
COMMENT = 'Governed catalog of reusable agent procedures';

CREATE TABLE IF NOT EXISTS PROCEDURE_VERSIONS (
    PROCEDURE_VERSION_ID VARCHAR(64) NOT NULL,
    PROCEDURE_ID         VARCHAR(64) NOT NULL,
    VERSION_NUMBER       NUMBER(10,0) NOT NULL,
    PROCEDURE_STEPS      VARIANT NOT NULL,
    GUARDRAILS           VARIANT,
    INPUT_CONTRACT       VARIANT,
    OUTPUT_CONTRACT      VARIANT,
    APPROVAL_STATUS      VARCHAR(30) DEFAULT 'DRAFT',
    APPROVED_BY          VARCHAR(100),
    APPROVED_AT          TIMESTAMP_NTZ,
    EFFECTIVE_FROM       TIMESTAMP_NTZ,
    EFFECTIVE_TO         TIMESTAMP_NTZ,
    CREATED_AT           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_PROCEDURE_VERSIONS
        PRIMARY KEY (PROCEDURE_VERSION_ID),

    CONSTRAINT FK_PROCEDURE_VERSION_CATALOG
        FOREIGN KEY (PROCEDURE_ID)
        REFERENCES PROCEDURE_CATALOG(PROCEDURE_ID),

    CONSTRAINT UQ_PROCEDURE_VERSION
        UNIQUE (PROCEDURE_ID, VERSION_NUMBER)
)
COMMENT = 'Versioned procedure definitions and approval metadata';

