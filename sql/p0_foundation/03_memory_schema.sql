-- ============================================================
-- P0-D2: Persistent Agent Memory Foundation
-- Snowflake Agentic AI Memory Lighthouse
-- ============================================================

USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE ECOM_AGENT_MEMORY_WH;
USE DATABASE ECOM_AGENT_MEMORY_DB;
USE SCHEMA MEMORY;

-- 1. Conversation metadata
CREATE TABLE IF NOT EXISTS CONVERSATION_METADATA (
    CONVERSATION_ID       VARCHAR(64) NOT NULL,
    CUSTOMER_ID           VARCHAR(30) NOT NULL,
    AGENT_ID              VARCHAR(100),
    CHANNEL               VARCHAR(30),
    CONVERSATION_STATUS   VARCHAR(30) DEFAULT 'ACTIVE',
    STARTED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    ENDED_AT              TIMESTAMP_NTZ,
    METADATA              VARIANT,
    CREATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_CONVERSATION_METADATA
        PRIMARY KEY (CONVERSATION_ID),

    CONSTRAINT FK_CONVERSATION_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES ECOM_AGENT_MEMORY_DB.RAW.CUSTOMERS(CUSTOMER_ID)
)
COMMENT = 'Conversation ownership and lifecycle metadata';

-- 2. Session state
CREATE TABLE IF NOT EXISTS SESSION_STATE (
    SESSION_ID            VARCHAR(64) NOT NULL,
    CONVERSATION_ID       VARCHAR(64) NOT NULL,
    CUSTOMER_ID           VARCHAR(30) NOT NULL,
    STATE_KEY             VARCHAR(100) NOT NULL,
    STATE_VALUE           VARIANT,
    STATE_VERSION         NUMBER(10,0) DEFAULT 1,
    EXPIRES_AT            TIMESTAMP_NTZ,
    CREATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_SESSION_STATE
        PRIMARY KEY (SESSION_ID, STATE_KEY),

    CONSTRAINT FK_SESSION_CONVERSATION
        FOREIGN KEY (CONVERSATION_ID)
        REFERENCES CONVERSATION_METADATA(CONVERSATION_ID)
)
COMMENT = 'Short-term agent working memory with expiration';

-- 3. Episodic memory
CREATE TABLE IF NOT EXISTS EPISODIC_MEMORY (
    MEMORY_ID             VARCHAR(64) NOT NULL,
    CUSTOMER_ID           VARCHAR(30) NOT NULL,
    CONVERSATION_ID       VARCHAR(64),
    EVENT_TYPE            VARCHAR(100) NOT NULL,
    MEMORY_TEXT           VARCHAR(4000) NOT NULL,
    MEMORY_PAYLOAD        VARIANT,
    SOURCE_REFERENCE      VARCHAR(200),
    CONFIDENCE_SCORE      FLOAT,
    MEMORY_STATUS         VARCHAR(30) DEFAULT 'ACTIVE',
    OCCURRED_AT           TIMESTAMP_NTZ,
    EXPIRES_AT            TIMESTAMP_NTZ,
    CREATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_EPISODIC_MEMORY
        PRIMARY KEY (MEMORY_ID),

    CONSTRAINT FK_EPISODIC_CONVERSATION
        FOREIGN KEY (CONVERSATION_ID)
        REFERENCES CONVERSATION_METADATA(CONVERSATION_ID)
)
COMMENT = 'Persistent historical events and agent interaction memories';

-- 4. Semantic memory
CREATE TABLE IF NOT EXISTS SEMANTIC_MEMORY (
    MEMORY_ID             VARCHAR(64) NOT NULL,
    CUSTOMER_ID           VARCHAR(30) NOT NULL,
    FACT_CATEGORY         VARCHAR(100) NOT NULL,
    FACT_KEY              VARCHAR(200) NOT NULL,
    FACT_VALUE            VARIANT,
    FACT_TEXT             VARCHAR(4000),
    SOURCE_REFERENCE      VARCHAR(200),
    CONFIDENCE_SCORE      FLOAT,
    MEMORY_VERSION        NUMBER(10,0) DEFAULT 1,
    MEMORY_STATUS         VARCHAR(30) DEFAULT 'ACTIVE',
    VALID_FROM            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO              TIMESTAMP_NTZ,
    EXPIRES_AT            TIMESTAMP_NTZ,
    CREATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_SEMANTIC_MEMORY
        PRIMARY KEY (MEMORY_ID)
)
COMMENT = 'Versioned durable customer facts and preferences';

-- 5. Memory audit
CREATE TABLE IF NOT EXISTS MEMORY_AUDIT (
    AUDIT_ID              VARCHAR(64) NOT NULL,
    MEMORY_ID             VARCHAR(64),
    CUSTOMER_ID           VARCHAR(30),
    MEMORY_TYPE           VARCHAR(30),
    OPERATION_TYPE        VARCHAR(30) NOT NULL,
    ACTOR_TYPE            VARCHAR(30),
    ACTOR_ID              VARCHAR(100),
    CONVERSATION_ID       VARCHAR(64),
    OPERATION_REASON      VARCHAR(1000),
    BEFORE_VALUE          VARIANT,
    AFTER_VALUE           VARIANT,
    OPERATION_STATUS      VARCHAR(30),
    EVENT_TIMESTAMP       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_MEMORY_AUDIT
        PRIMARY KEY (AUDIT_ID)
)
COMMENT = 'Append-oriented audit history for governed memory operations';

-- Standard Snowflake PK/FK constraints are informational.
-- Runtime ownership and authorization checks will be
-- implemented and evaluated in later milestones.
-- No memory records are inserted in P0.