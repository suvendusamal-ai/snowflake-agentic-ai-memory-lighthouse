USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE DATABASE ECOM_AGENT_MEMORY_DB;

DESCRIBE TABLE MEMORY.CONVERSATION_METADATA;

DESCRIBE TABLE MEMORY.SESSION_STATE;

DESCRIBE TABLE MEMORY.MEMORY_AUDIT;

SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE,
    COLUMN_DEFAULT,
    ORDINAL_POSITION
FROM ECOM_AGENT_MEMORY_DB.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'MEMORY'
  AND TABLE_NAME IN (
      'CONVERSATION_METADATA',
      'SESSION_STATE',
      'MEMORY_AUDIT'
  )
ORDER BY TABLE_NAME, ORDINAL_POSITION;

SELECT
    TABLE_NAME,
    CONSTRAINT_NAME,
    CONSTRAINT_TYPE
FROM ECOM_AGENT_MEMORY_DB.INFORMATION_SCHEMA.TABLE_CONSTRAINTS
WHERE TABLE_SCHEMA = 'MEMORY'
  AND TABLE_NAME IN (
      'CONVERSATION_METADATA',
      'SESSION_STATE',
      'MEMORY_AUDIT'
  )
ORDER BY TABLE_NAME, CONSTRAINT_NAME;