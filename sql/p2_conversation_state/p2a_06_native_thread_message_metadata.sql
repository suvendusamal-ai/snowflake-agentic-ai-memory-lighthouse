USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE WAREHOUSE ECOM_AGENT_MEMORY_WH;

WITH THREAD_DATA AS (
    SELECT TRY_PARSE_JSON(
        SNOWFLAKE.CORTEX.THREAD_MESSAGES(89390720)
    ) AS HISTORY
)
SELECT
    TYPEOF(HISTORY:messages) AS MESSAGES_TYPE,
    ARRAY_SIZE(HISTORY:messages) AS MESSAGE_COUNT
FROM THREAD_DATA;

WITH THREAD_DATA AS (
    SELECT TRY_PARSE_JSON(
        SNOWFLAKE.CORTEX.THREAD_MESSAGES(89390720)
    ) AS HISTORY
)
SELECT
    F.INDEX AS MESSAGE_INDEX,
    F.VALUE:message_id::NUMBER AS MESSAGE_ID,
    F.VALUE:role::VARCHAR AS MESSAGE_ROLE,
    F.VALUE:created_on::NUMBER AS CREATED_ON,
    F.VALUE:is_compressed::BOOLEAN AS IS_COMPRESSED,
    F.VALUE:compression_alg::VARCHAR AS COMPRESSION_ALGORITHM,
    TYPEOF(F.VALUE:message_payload) AS PAYLOAD_TYPE,
    LENGTH(F.VALUE:message_payload::VARCHAR) AS PAYLOAD_LENGTH
FROM THREAD_DATA,
LATERAL FLATTEN(INPUT => HISTORY:messages) F
ORDER BY F.INDEX;