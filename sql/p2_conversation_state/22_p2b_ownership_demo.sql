USE ROLE ECOM_AGENT_MEMORY_OWNER;

INSERT INTO ECOM_AGENT_MEMORY_DB.MEMORY.CONVERSATION_METADATA
    (CONVERSATION_ID, CUSTOMER_ID, OWNER_ID, AGENT_ID, CONVERSATION_STATUS)
SELECT
    'P2B_AUTH_DEMO_001',
    CUSTOMER_ID,
    'USER_A',
    'ECOM_STATELESS_AGENT',
    'ACTIVE'
FROM ECOM_AGENT_MEMORY_DB.RAW.CUSTOMERS
ORDER BY CUSTOMER_ID
LIMIT 1;

WITH TESTS AS (
    SELECT 'TC-01 Own conversation' AS TEST, 'USER_A' AS ACTOR, 'ALLOW' AS EXPECTED
    UNION ALL
    SELECT 'TC-02 Cross-user', 'USER_B', 'DENY'
    UNION ALL
    SELECT 'TC-03 Missing identity', NULL, 'DENY'
),
RESULTS AS (
    SELECT
        T.TEST,
        T.EXPECTED,
        IFF(
            T.ACTOR IS NOT NULL
            AND C.OWNER_ID = T.ACTOR
            AND C.CONVERSATION_STATUS = 'ACTIVE',
            'ALLOW',
            'DENY'
        ) AS ACTUAL
    FROM TESTS T
    CROSS JOIN ECOM_AGENT_MEMORY_DB.MEMORY.CONVERSATION_METADATA C
    WHERE C.CONVERSATION_ID = 'P2B_AUTH_DEMO_001'
)
SELECT
    TEST,
    EXPECTED,
    ACTUAL,
    IFF(EXPECTED = ACTUAL, 'PASS', 'FAIL') AS RESULT
FROM RESULTS
ORDER BY TEST;