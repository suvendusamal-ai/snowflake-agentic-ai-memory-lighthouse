USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE WAREHOUSE ECOM_AGENT_MEMORY_WH;
USE DATABASE ECOM_AGENT_MEMORY_DB;

SELECT
    CURRENT_ROLE()      AS CURRENT_ROLE,
    CURRENT_WAREHOUSE() AS CURRENT_WAREHOUSE,
    CURRENT_DATABASE()  AS CURRENT_DATABASE;

SHOW SCHEMAS IN DATABASE ECOM_AGENT_MEMORY_DB;

SHOW TABLES IN DATABASE ECOM_AGENT_MEMORY_DB;

SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    TABLE_TYPE,
    CREATED,
    LAST_ALTERED
FROM ECOM_AGENT_MEMORY_DB.INFORMATION_SCHEMA.TABLES
WHERE
       UPPER(TABLE_NAME) LIKE '%CONVERSATION%'
    OR UPPER(TABLE_NAME) LIKE '%THREAD%'
    OR UPPER(TABLE_NAME) LIKE '%MEMORY%'
    OR UPPER(TABLE_NAME) LIKE '%REGISTRY%'
    OR UPPER(TABLE_NAME) LIKE '%STATE%'
ORDER BY TABLE_SCHEMA, TABLE_NAME;