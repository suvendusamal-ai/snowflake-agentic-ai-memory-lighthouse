USE ROLE ECOM_AGENT_MEMORY_OWNER;
USE WAREHOUSE ECOM_AGENT_MEMORY_WH;

WITH THREAD_DATA AS (
    SELECT TRY_PARSE_JSON(
        SNOWFLAKE.CORTEX.THREAD_MESSAGES(89390720)
    ) AS HISTORY
)
SELECT
    TYPEOF(HISTORY) AS HISTORY_TYPE,
    CASE
        WHEN IS_ARRAY(HISTORY) THEN ARRAY_SIZE(HISTORY)
        ELSE NULL
    END AS MESSAGE_COUNT,
    LEFT(TO_VARCHAR(HISTORY), 1000) AS HISTORY_PREVIEW
FROM THREAD_DATA;